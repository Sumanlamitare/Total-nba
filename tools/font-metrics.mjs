// Builds lib/graphics/metrics.js: advance widths (per 1000 em) for the fonts the graphics use, so text is measured the
// same way in the browser editor and in server rendering (resvg).  node tools/font-metrics.mjs
import opentype from 'opentype.js';
import fs from 'node:fs';
const FONTS = {
  'display-600': 'BarlowCondensed-600.ttf', 'display-700': 'BarlowCondensed-700.ttf', 'display-800': 'BarlowCondensed-800.ttf', 'display-900': 'BarlowCondensed-900.ttf', 'display-800i': 'BarlowCondensed-800i.ttf',
  'sans-400': 'Inter_400Regular.ttf', 'sans-600': 'Inter_600SemiBold.ttf', 'sans-700': 'Inter_700Bold.ttf', 'sans-800': 'Inter_800ExtraBold.ttf',
};
const chars = [];
for (let c = 32; c <= 383; c++) chars.push(c);
for (const c of '–—‘’“”•·×…€′″→↑↓★✓') chars.push(c.codePointAt(0));
const out = { chars: String.fromCodePoint(...chars), fonts: {} };
for (const [k, f] of Object.entries(FONTS)) {
  const buf = fs.readFileSync(`lib/fonts/${f}`); const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const s = 1000 / font.unitsPerEm;
  out.fonts[k] = { asc: Math.round(font.ascender * s), desc: Math.round(-font.descender * s), cap: Math.round((font.tables.os2?.sCapHeight || font.ascender * 0.7) * s),
    w: chars.map(c => Math.round((font.charToGlyph(String.fromCodePoint(c)).advanceWidth || 0) * s)) };
}
fs.writeFileSync('lib/graphics/metrics.js', `// Generated by tools/font-metrics.mjs — advance widths per 1000 em.\nexport default ${JSON.stringify(out)};\n`);
console.log(Object.keys(out.fonts), out.chars.length);
