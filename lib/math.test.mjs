import * as M from './math.js';
const ok = (c, m) => { if (!c) { console.error('FAIL', m); process.exitCode = 1; } else console.log('ok', m); };
const near = (a, b, t = 0.005) => Math.abs(a - b) < t;
ok(near(M.implied(-110), 0.5238), 'implied -110 = 52.4%');
ok(near(M.toDecimal(150), 2.5), 'decimal +150');
const [a, b] = M.devig(-110, -110); ok(near(a, 0.5) && near(b, 0.5), 'devig -110/-110 = 50/50');
ok(near(M.devig(-150, 130)[0], 0.5798, 0.002), 'devig -150/+130');
const [pa, pb] = M.devig(-150, 130, 'power'); ok(near(pa + pb, 1, 1e-6), 'power devig sums to 1');
ok(near(M.ev(0.55, -110), 0.05, 0.001), 'EV 55% at -110 = +5%');
ok(near(M.kelly(0.55, -110), 0.0136, 0.001), 'quarter Kelly');
ok(near(M.phi(1.96), 0.975, 0.001), 'normal CDF');
ok(near(M.normalLine(25, 6, 24.5).over, 0.5332, 0.002), 'normal over 24.5');
const w = M.normalLine(25, 6, 25); ok(near(w.over + w.under + w.push, 1, 1e-9) && w.push > 0.05, 'whole line has a push');
const pois = M.countLine(4, 4, 3.5); ok(near(pois.over, 0.5665, 0.002), 'Poisson over 3.5 at mean 4');
const nb = M.countLine(4, 8, 3.5); ok(nb.over < pois.over && nb.over > 0.45, 'neg. binomial is wider');
ok(near(M.countPmf(6, 9).reduce((x, y) => x + y, 0), 1, 0.01), 'neg. binomial sums to 1');
ok(near(M.blend(0.6, 0.5, 0.4), 0.5405, 0.003), 'log-odds blend');
const [lo, hi] = M.wilson(8, 10); ok(lo > 0.44 && hi < 0.95, 'Wilson interval 8/10');
